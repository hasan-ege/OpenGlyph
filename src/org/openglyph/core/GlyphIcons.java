    private GlyphIcons() {}

    public static List<String> names() {
        return List.copyOf(ICONS.keySet());
    }

    public static boolean exists(String name) {
        return ICONS.containsKey(name);
    }

    /** The icon as a 625-entry grid at {@code value}, centred; null for an unknown name. */
    public static int[] render(String name, int value) {
        String[] rows = ICONS.get(name);
        if (rows == null) return null;
        int w = 0;
        for (String r : rows) w = Math.max(w, r.length());
        int x0 = (MatrixLayout.WIDTH - w) / 2;
        int y0 = (MatrixLayout.HEIGHT - rows.length) / 2;
        int[] grid = new int[MatrixLayout.GRID_SIZE];
        for (int y = 0; y < rows.length; y++) {
            for (int x = 0; x < rows[y].length(); x++) {
                if (rows[y].charAt(x) == '#') grid[(y0 + y) * MatrixLayout.WIDTH + x0 + x] = value;
            }
        }
        return grid;
    }
